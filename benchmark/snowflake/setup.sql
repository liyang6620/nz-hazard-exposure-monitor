-- Render with render_setup.py after the trial credit balance and key are known.
-- Execute the complete script as ACCOUNTADMIN in one Snowsight Worksheet.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS NZHEM_TRIAL_GUARD
  WITH CREDIT_QUOTA = {{TRIAL_CREDIT_QUOTA}}
  FREQUENCY = NEVER
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS NZHEM_XS
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS NZHEM_BENCHMARK;
CREATE SCHEMA IF NOT EXISTS NZHEM_BENCHMARK.CURATED;
CREATE SCHEMA IF NOT EXISTS NZHEM_BENCHMARK.BENCHMARK_FULL;
CREATE SCHEMA IF NOT EXISTS NZHEM_BENCHMARK.BENCHMARK_SINGLE;
CREATE STAGE IF NOT EXISTS NZHEM_BENCHMARK.CURATED.LOCAL_PARQUET
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE FILE FORMAT IF NOT EXISTS NZHEM_BENCHMARK.CURATED.PARQUET_FORMAT
  TYPE = PARQUET
  BINARY_AS_TEXT = FALSE;
ALTER FILE FORMAT NZHEM_BENCHMARK.CURATED.PARQUET_FORMAT
  SET BINARY_AS_TEXT = FALSE;

ALTER WAREHOUSE NZHEM_XS SET RESOURCE_MONITOR = NZHEM_TRIAL_GUARD;

CREATE ROLE IF NOT EXISTS NZHEM_BENCHMARK_ROLE;
CREATE USER IF NOT EXISTS NZHEM_BENCHMARK_USER
  TYPE = SERVICE
  RSA_PUBLIC_KEY = '{{RSA_PUBLIC_KEY}}'
  DEFAULT_ROLE = NZHEM_BENCHMARK_ROLE
  DEFAULT_WAREHOUSE = NZHEM_XS;
ALTER USER NZHEM_BENCHMARK_USER SET RSA_PUBLIC_KEY = '{{RSA_PUBLIC_KEY}}';
GRANT ROLE NZHEM_BENCHMARK_ROLE TO USER NZHEM_BENCHMARK_USER;
GRANT USAGE ON WAREHOUSE NZHEM_XS TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT OPERATE ON WAREHOUSE NZHEM_XS TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT USAGE ON DATABASE NZHEM_BENCHMARK TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE NZHEM_BENCHMARK TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT CREATE TABLE ON SCHEMA NZHEM_BENCHMARK.CURATED TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT CREATE TABLE ON SCHEMA NZHEM_BENCHMARK.BENCHMARK_FULL TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT CREATE TABLE ON SCHEMA NZHEM_BENCHMARK.BENCHMARK_SINGLE TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT CREATE VIEW ON SCHEMA NZHEM_BENCHMARK.BENCHMARK_FULL TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT CREATE VIEW ON SCHEMA NZHEM_BENCHMARK.BENCHMARK_SINGLE TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT READ, WRITE ON STAGE NZHEM_BENCHMARK.CURATED.LOCAL_PARQUET TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT USAGE ON FILE FORMAT NZHEM_BENCHMARK.CURATED.PARQUET_FORMAT TO ROLE NZHEM_BENCHMARK_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NZHEM_BENCHMARK.CURATED TO ROLE NZHEM_BENCHMARK_ROLE;
